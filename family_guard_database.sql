begin;

create extension if not exists pgcrypto;

-- ============================================================
-- 1. USER PROFILE
--    role: 'nguoichamsoc' (caregiver) | 'nguoiduocchamsoc' (cared person)
--    NOTE: column "avata" (not avatar) is the name used by the code.
-- ============================================================
create table if not exists public.user_info (
  uid        uuid primary key references auth.users(id) on delete cascade,
  name       text not null default '',
  email      text,
  phone      text,
  birthday   date,
  sex        text,
  address    text,
  role       text not null default 'nguoiduocchamsoc'
             check (role in ('nguoichamsoc', 'nguoiduocchamsoc')),
  user_type  text,
  avata      text,
  created_at timestamptz not null default now()
);

create index if not exists idx_user_info_email on public.user_info (email);
create index if not exists idx_user_info_phone on public.user_info (phone);

-- Auto-create a profile row whenever a new Auth user is created
-- (backend also creates it on first login, this is just a safety net).
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.user_info (uid, email, name, phone, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    new.raw_user_meta_data ->> 'phone',
    case
      when new.raw_user_meta_data ->> 'role' in ('nguoichamsoc', 'nguoiduocchamsoc')
        then new.raw_user_meta_data ->> 'role'
      else 'nguoiduocchamsoc'
    end
  )
  on conflict (uid) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

-- ============================================================
-- 2. RELATIONSHIP
--    processing: 'chuachapnhan' (pending) | 'xacnhan' (confirmed)
--                | 'huy' (declined) | 'daxoa' (deleted)
--    FK names relationship_uid_fkey / relationship_relation_id_fkey
--    are REQUIRED (used by PostgREST embeds in the backend).
-- ============================================================
create table if not exists public.relationship (
  id                    bigint generated by default as identity primary key,
  uid                   uuid not null,
  relation_id           uuid not null,
  relation_type         text,
  reverse_relation_type text,
  processing            text not null default 'chuachapnhan'
                        check (processing in ('chuachapnhan', 'xacnhan', 'huy', 'daxoa')),
  created_at            timestamptz not null default now(),
  constraint relationship_uid_fkey
    foreign key (uid) references public.user_info(uid) on delete cascade,
  constraint relationship_relation_id_fkey
    foreign key (relation_id) references public.user_info(uid) on delete cascade,
  constraint relationship_uid_relation_id_key unique (uid, relation_id),
  constraint relationship_not_self check (uid <> relation_id)
);

create index if not exists idx_relationship_uid on public.relationship (uid);
create index if not exists idx_relationship_relation_id on public.relationship (relation_id);

-- ============================================================
-- 3. NOTIFICATION
--    processing: 'dagui' (sent, waiting response) | 'done'
-- ============================================================
create table if not exists public.notification (
  id              bigint generated by default as identity primary key,
  uid             uuid not null references public.user_info(uid) on delete cascade,
  relationship_id bigint references public.relationship(id) on delete set null,
  title           text not null default '',
  content         text not null default '',
  processing      text not null default 'done',
  fall_latitude   double precision,
  fall_longitude  double precision,
  created_at      timestamptz not null default now()
);

create index if not exists idx_notification_uid_created
  on public.notification (uid, created_at desc);

-- ============================================================
-- 4. LOCATIONS
-- ============================================================
create table if not exists public.user_locations (
  uid        uuid primary key references public.user_info(uid) on delete cascade,
  latitude   double precision not null,
  longitude  double precision not null,
  accuracy   double precision,
  speed      double precision,
  address    text,
  street     text,
  ward       text,
  district   text,
  city       text,
  country    text,
  place_name text,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.location_history (
  id         bigint generated always as identity primary key,
  uid        uuid not null references public.user_info(uid) on delete cascade,
  latitude   double precision not null,
  longitude  double precision not null,
  accuracy   double precision,
  speed      double precision,
  address    text,
  street     text,
  ward       text,
  district   text,
  city       text,
  country    text,
  place_name text,
  created_at timestamptz not null default now()
);

create index if not exists idx_location_history_uid_created_at
  on public.location_history (uid, created_at desc);

-- ============================================================
-- 5. SAFE ZONES
-- ============================================================
create table if not exists public.safe_zones (
  id               bigint generated always as identity primary key,
  owner_uid        uuid not null references public.user_info(uid) on delete cascade,
  target_uid       uuid not null references public.user_info(uid) on delete cascade,
  name             text not null,
  center_latitude  double precision not null,
  center_longitude double precision not null,
  radius_meters    integer not null check (radius_meters > 0),
  is_active        boolean not null default true,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create table if not exists public.safe_zone_states (
  id               bigint generated always as identity primary key,
  safe_zone_id     bigint not null references public.safe_zones(id) on delete cascade,
  uid              uuid not null references public.user_info(uid) on delete cascade,
  is_inside        boolean not null,
  last_checked_at  timestamptz not null default now(),
  last_notified_at timestamptz,
  unique (safe_zone_id, uid)
);

create index if not exists idx_safe_zones_owner_uid on public.safe_zones (owner_uid);
create index if not exists idx_safe_zones_target_uid on public.safe_zones (target_uid);
create index if not exists idx_safe_zones_target_uid_active on public.safe_zones (target_uid, is_active);
create index if not exists idx_safe_zone_states_uid on public.safe_zone_states (uid);

-- ============================================================
-- 6. CHAT
-- ============================================================
create table if not exists public.chat_message (
  id              bigserial primary key,
  relationship_id bigint not null references public.relationship(id) on delete cascade,
  sender_uid      uuid not null references public.user_info(uid) on delete cascade,
  receiver_uid    uuid not null references public.user_info(uid) on delete cascade,
  content         text not null,
  is_read         boolean not null default false,
  created_at      timestamptz not null default now()
);

create index if not exists idx_chat_message_pair_created
  on public.chat_message (sender_uid, receiver_uid, created_at desc);

create table if not exists public.chat_presence (
  uid             uuid primary key references public.user_info(uid) on delete cascade,
  active_peer_uid uuid null,
  updated_at      timestamptz not null default now()
);

-- ============================================================
-- 7. PUSH DEVICE TOKENS (FCM)
-- ============================================================
create table if not exists public.user_device_tokens (
  id         bigserial primary key,
  uid        uuid not null references auth.users(id) on delete cascade,
  token      text not null unique,
  platform   text null,
  device_id  text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists user_device_tokens_uid_idx on public.user_device_tokens (uid);

-- ============================================================
-- 8. KID REMINDER
--    schedule_type: 'daily' | 'once' | 'weekly'
--    weekdays: 1..7 (Mon..Sun)
-- ============================================================
create table if not exists public.kid_reminder (
  id            bigserial primary key,
  owner_uid     uuid not null references public.user_info(uid) on delete cascade,
  member_uid    uuid not null references public.user_info(uid) on delete cascade,
  title         text not null,
  reminder_time text not null,
  schedule_type text not null default 'daily',
  schedule_date date,
  weekdays      int[] not null default '{}',
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists kid_reminder_owner_member_idx on public.kid_reminder (owner_uid, member_uid);
create index if not exists kid_reminder_member_idx on public.kid_reminder (member_uid);

-- ============================================================
-- 9. REALTIME: replica identity (needed for filtered realtime)
-- ============================================================
alter table public.notification   replica identity full;
alter table public.relationship   replica identity full;
alter table public.user_locations replica identity full;
alter table public.safe_zones     replica identity full;
alter table public.chat_message   replica identity full;

-- ============================================================
-- 10. ROW LEVEL SECURITY
--     Backend uses the service_role key (bypasses RLS).
--     These SELECT policies are for the Flutter Realtime client.
-- ============================================================
alter table public.user_info          enable row level security;
alter table public.relationship       enable row level security;
alter table public.notification       enable row level security;
alter table public.user_locations     enable row level security;
alter table public.location_history   enable row level security;
alter table public.safe_zones         enable row level security;
alter table public.safe_zone_states   enable row level security;
alter table public.chat_message       enable row level security;
alter table public.chat_presence      enable row level security;
alter table public.user_device_tokens enable row level security;
alter table public.kid_reminder       enable row level security;

drop policy if exists user_info_select_own on public.user_info;
create policy user_info_select_own on public.user_info
  for select to authenticated using (uid = auth.uid());

drop policy if exists relationship_select_own_uid on public.relationship;
create policy relationship_select_own_uid on public.relationship
  for select to authenticated using (uid = auth.uid() or relation_id = auth.uid());

drop policy if exists notification_select_own_uid on public.notification;
create policy notification_select_own_uid on public.notification
  for select to authenticated using (uid = auth.uid());

-- Own location + locations of confirmed family members (for live map).
drop policy if exists user_locations_select_own_uid on public.user_locations;
drop policy if exists user_locations_select_own_or_family on public.user_locations;
create policy user_locations_select_own_or_family on public.user_locations
  for select to authenticated using (
    uid = auth.uid()
    or exists (
      select 1 from public.relationship r
      where r.processing = 'xacnhan'
        and ((r.uid = auth.uid() and r.relation_id = user_locations.uid)
          or (r.relation_id = auth.uid() and r.uid = user_locations.uid))
    )
  );

drop policy if exists location_history_select_own_uid on public.location_history;
create policy location_history_select_own_uid on public.location_history
  for select to authenticated using (uid = auth.uid());

drop policy if exists safe_zones_select_owner_or_target on public.safe_zones;
create policy safe_zones_select_owner_or_target on public.safe_zones
  for select to authenticated using (owner_uid = auth.uid() or target_uid = auth.uid());

drop policy if exists safe_zone_states_select_own_uid on public.safe_zone_states;
create policy safe_zone_states_select_own_uid on public.safe_zone_states
  for select to authenticated using (uid = auth.uid());

drop policy if exists chat_message_select_own on public.chat_message;
create policy chat_message_select_own on public.chat_message
  for select to authenticated using (sender_uid = auth.uid() or receiver_uid = auth.uid());

drop policy if exists chat_presence_select_own on public.chat_presence;
create policy chat_presence_select_own on public.chat_presence
  for select to authenticated using (uid = auth.uid());

drop policy if exists "Users can manage own device tokens" on public.user_device_tokens;
create policy "Users can manage own device tokens" on public.user_device_tokens
  for all using (auth.uid() = uid) with check (auth.uid() = uid);

drop policy if exists kid_reminder_select_owner_or_member on public.kid_reminder;
create policy kid_reminder_select_owner_or_member on public.kid_reminder
  for select to authenticated using (owner_uid = auth.uid() or member_uid = auth.uid());

-- ============================================================
-- 11. REALTIME PUBLICATION
-- ============================================================
do $$
declare
  t text;
begin
  foreach t in array array['notification', 'relationship', 'user_locations', 'safe_zones', 'chat_message']
  loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', t);
    exception when duplicate_object then null;
    end;
  end loop;
end $$;

-- ============================================================
-- 12. STORAGE: public bucket "avatars" (used by POST /users/me/avatar)
-- ============================================================
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do update set public = true;

commit;

